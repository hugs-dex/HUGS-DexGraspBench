def load_hand_wrist_approach_axes(hand_name: str) -> Any:
    """Load wrist approach axes from one benchmark hand config.

    Args:
        hand_name: Hand config name, such as `shadow` or `dual_dummy_arm_shadow`.

    Returns:
        Configured `wrist_approach_axes`, or the legacy default axis when the
        hand config does not define the field.
    """

    hand_config_path = REPO_ROOT / "config" / "hand" / f"{hand_name}.yaml"
    hand_config = OmegaConf.load(hand_config_path)
    approach_axes = hand_config.get("wrist_approach_axes")
    if approach_axes is None:
        return DEFAULT_WRIST_APPROACH_AXIS
    return OmegaConf.to_container(approach_axes, resolve=True)


def build_stat_jobs(
    hand_family: str,
    run_name: str,
    save_root: Path,
    grasp_types: list[str] | None,
    include_both_three: bool = True,
) -> list[StatJob]:
    """Create stat jobs with the same output naming as the all-type evaluation script.

    Args:
        hand_family: Hand family requested by CLI, one of `shadow` or `leap_sp`.
        run_name: Base run name used during evaluation.
        save_root: Root output folder containing per-type output folders.
        grasp_types: Optional selected grasp type names.
        include_both_three: Whether to keep `both_three` in the selected grasp
            types. When False, `both_three` is removed before any data is loaded.

    Returns:
        Ordered list of stat jobs.
    """

    selected_grasp_types = set(grasp_types or GRASP_TYPE_NAMES)
    if not include_both_three:
        selected_grasp_types.discard("both_three")
    hand_config = HAND_CONFIGS[hand_family]
    jobs = []
    for suffix, hand_kind, _tabletop_split in GRASP_TYPES:
        if suffix not in selected_grasp_types:
            continue
        hand_name = hand_config[f"{hand_kind}_hand"]
        output_path = save_root / f"{run_name}_{suffix}_{hand_name}"
        jobs.append(
            StatJob(
                grasp_type=suffix,
                hand_name=hand_name,
                output_path=output_path,
                wrist_approach_axes=load_hand_wrist_approach_axes(hand_name),
            )
        )
    return jobs


def scene_id_from_eval_path(eval_path: Path, eval_dir: Path) -> str:
    """Convert one evaluation file path into a scene identifier.

    Args:
        eval_path: Path to one evaluated grasp `.npy` file.
        eval_dir: Root evaluation folder for the grasp type.

    Returns:
        POSIX-style relative parent path, e.g. `object/tabletop_ur10e/scale_pose`.
    """

    return eval_path.relative_to(eval_dir).parent.as_posix()


def success_from_data(data: dict[str, Any], rel_path: Path, succ_rel_paths: set[str]) -> bool:
    """Read a simulation success flag with a filesystem fallback.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.
        rel_path: File path relative to the evaluation directory.
        succ_rel_paths: Relative paths found under the matching `succgrasp` directory.

    Returns:
        True if the evaluated grasp succeeded; otherwise False.
    """

    if "succ_flag" in data:
        return bool(np.asarray(data["succ_flag"]).item())
    return rel_path.as_posix() in succ_rel_paths


def has_self_collision(data: dict[str, Any]) -> bool:
    """Check whether one evaluated grasp has any hand-hand contact penetration.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.

    Returns:
        True if `self_pene` exists and is strictly greater than zero; otherwise
        False. Missing or non-finite values are not treated as self-penetration
        failures here so older/early-failed eval files fall back to other reasons.
    """

    self_pene = scalar_float_from_data(data, "self_pene")
    return self_pene is not None and self_pene > 0.0


def hand_geom_distance_from_data(data: dict[str, Any]) -> float | None:
    """Read nearest hand-hand geom clearance from one evaluation record.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.

    Returns:
        Non-negative nearest hand-hand geom clearance in meters if
        `self_signed_dist` is available and finite; otherwise None. The eval
        field uses penetration-positive signed distance, so clearance is the
        negated signed distance.
    """

    signed_dist = scalar_float_from_data(data, "self_signed_dist")
    if signed_dist is None:
        return None
    return -signed_dist


def has_too_close_hand_geoms(data: dict[str, Any], hand_geom_dist_thre: float) -> bool:
    """Check whether nearest hand-hand geom clearance is below threshold.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.
        hand_geom_dist_thre: Minimum allowed nearest hand-hand geom clearance in meters.

    Returns:
        True if the nearest hand-hand geom clearance exists and is smaller than
        `hand_geom_dist_thre`; otherwise False.
    """

    geom_distance = hand_geom_distance_from_data(data)
    return geom_distance is not None and geom_distance < hand_geom_dist_thre


def scalar_float_from_data(data: dict[str, Any], key: str) -> float | None:
    """Read one scalar float from an evaluation dictionary.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.
        key: Field name to read, such as `delta_pos` or `delta_angle`.

    Returns:
        Scalar float value if the field exists and contains one scalar; otherwise None.
    """

    if key not in data:
        return None
    value_array = np.asarray(data[key], dtype=np.float64)
    if value_array.size != 1:
        return None
    value = float(value_array.item())
    return value if np.isfinite(value) else None


def object_scale_key_from_data(data: dict[str, Any]) -> str:
    """Read a stable object-scale key from one evaluation dictionary.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.

    Returns:
        Printable object-scale key. Missing or invalid values are grouped as
        `unknown`.
    """

    scale_value = scalar_float_from_data(data, "obj_scale")
    if scale_value is None:
        return "unknown"
    return f"{scale_value:.6g}"


def object_scale_sort_key(scale_key: str) -> tuple[int, float | str]:
    """Build a stable sort key for object-scale summary rows.

    Args:
        scale_key: Printable object-scale key.

    Returns:
        Tuple that sorts numeric scales first and non-numeric keys last.
    """

    try:
        return (0, float(scale_key))
    except ValueError:
        return (1, scale_key)


def summarize_scalar_metric(records: list[EvalRecord], metric_key: str) -> dict[str, Any]:
    """Summarize one scalar metric over evaluation records.

    Args:
        records: Evaluation records to inspect.
        metric_key: Scalar metric field name, such as `qp_metric`.

    Returns:
        JSON-serializable metric statistics. `count` is the number of records
        with a finite scalar value for `metric_key`; aggregate values are None
        when no finite value exists.
    """

    values = [
        metric_value
        for record in records
        for metric_value in [scalar_float_from_data(record.data, metric_key)]
        if metric_value is not None
    ]
    if not values:
        return {
            "metric": metric_key,
            "count": 0,
            "mean": None,
            "std": None,
            "median": None,
            "min": None,
            "max": None,
        }

    value_array = np.asarray(values, dtype=np.float64)
    return {
        "metric": metric_key,
        "count": int(value_array.size),
        "mean": float(np.mean(value_array)),
        "std": float(np.std(value_array)),
        "median": float(np.median(value_array)),
        "min": float(np.min(value_array)),
        "max": float(np.max(value_array)),
    }


def classify_failure_reason(
    data: dict[str, Any],
    success: bool,
    trans_thre: float,
    angle_thre: float,
    hand_geom_dist_thre: float,
) -> str | None:
    """Classify one failed grasp into the main simulation failure reasons.

    Args:
        data: Evaluation dictionary loaded from an `.npy` file.
        success: Whether this grasp succeeded in simulation.
        trans_thre: Translation threshold used by evaluation success checks.
        angle_thre: Rotation threshold in degrees used by evaluation success checks.
        hand_geom_dist_thre: Minimum allowed nearest hand-hand geom clearance in meters.

    Returns:
        Failure reason key for failed grasps, None for successful grasps.
    """

    if success:
        return None

    delta_pos = scalar_float_from_data(data, "delta_pos")
    delta_angle = scalar_float_from_data(data, "delta_angle")
    if has_self_collision(data):
        return "self_penetration"
    if has_too_close_hand_geoms(data, hand_geom_dist_thre):
        return "self_geom_distance"

    # `_eval_simulate_under_extforce` records this sentinel when initial hand-object
    # or hand-hand penetration exceeds `task.simulation_metrics.max_pene`.
    if (
        delta_pos is not None
        and delta_angle is not None
        and delta_pos >= SEVERE_PENETRATION_SENTINEL
        and delta_angle >= SEVERE_PENETRATION_SENTINEL
    ):
        return "pregrasp_severe_penetration"

    if delta_pos is None or delta_angle is None:
        return "unknown"

    # Position failure is assigned before rotation because an object that was not
    # lifted/stabilized enough may also show a large final rotation.
    if delta_pos >= trans_thre:
        return "position_error"
    if delta_angle >= angle_thre:
        return "rotation_error"
    return "unknown"


def summarize_failure_reasons(
    records: list[EvalRecord],
    trans_thre: float,
    angle_thre: float,
    hand_geom_dist_thre: float,
) -> dict[str, Any]:
    """Summarize failure-reason counts and rates for one grasp type.

    Args:
        records: Loaded evaluation records for one grasp type.
        trans_thre: Translation threshold used to classify position-error failures.
        angle_thre: Rotation threshold in degrees used to classify rotation-only failures.
        hand_geom_dist_thre: Minimum allowed nearest hand-hand geom clearance in meters.

    Returns:
        JSON-serializable dictionary containing counts and ratios for each reason.
    """

    reason_counts = Counter()
    failed_count = 0
    for record in records:
        reason = classify_failure_reason(record.data, record.success, trans_thre, angle_thre, hand_geom_dist_thre)
        if reason is None:
            continue
        failed_count += 1
        reason_counts[reason] += 1

    evaluated_count = len(records)
    by_reason = {}
    for reason_name in FAILURE_REASON_NAMES:
        count = reason_counts.get(reason_name, 0)
        by_reason[reason_name] = {
            "count": int(count),
            "failed_percent": float(count / failed_count) if failed_count else None,
            "evaluated_percent": float(count / evaluated_count) if evaluated_count else None,
        }

    return {
        "failed_grasps": int(failed_count),
        "by_reason": by_reason,
    }


def load_eval_records(job: StatJob, hand_geom_dist_thre: float) -> tuple[list[EvalRecord], list[str]]:
    """Load all evaluation records for one grasp type.

    Args:
        job: Stat job describing one grasp type output folder.
        hand_geom_dist_thre: Minimum allowed nearest hand-hand geom clearance used
            to override the raw simulation success flag.

    Returns:
        Pair of loaded records and warning messages collected while reading.
    """

    warnings = []
    if not job.eval_dir.exists():
        return [], [f"{job.grasp_type}: missing evaluation directory: {job.eval_dir}"]

    eval_paths = sorted(job.eval_dir.rglob("*.npy"))
    if not eval_paths:
        return [], [f"{job.grasp_type}: no evaluation files found in {job.eval_dir}"]

    succ_rel_paths = set()
    if job.succ_dir.exists():
        succ_rel_paths = {path.relative_to(job.succ_dir).as_posix() for path in job.succ_dir.rglob("*.npy")}

    records = []
    for eval_path in eval_paths:
        rel_path = eval_path.relative_to(job.eval_dir)
        data = np.load(eval_path, allow_pickle=True).item()
        data["_source_path"] = str(eval_path)
        raw_success = success_from_data(data, rel_path, succ_rel_paths)
        success = (
            raw_success
            and not has_self_collision(data)
            and not has_too_close_hand_geoms(data, hand_geom_dist_thre)
        )
        records.append(
            EvalRecord(
                scene_id=scene_id_from_eval_path(eval_path, job.eval_dir),
                success=success,
                data=data,
            )
        )
    return records, warnings


def metric_value_is_finite(metric_value: Any) -> bool:
    """Check whether a diversity metric value contains only finite numbers.

    Args:
        metric_value: Metric result, usually a list or a JSON-serializable dictionary.

    Returns:
        True when all numeric leaves are finite; otherwise False.
    """

    if isinstance(metric_value, dict):
        return all(metric_value_is_finite(value) for value in metric_value.values())
    if isinstance(metric_value, (list, tuple)):
        return all(metric_value_is_finite(value) for value in metric_value)
    if isinstance(metric_value, (str, bool)) or metric_value is None:
        return True
    try:
        return bool(np.isfinite(float(metric_value)))
    except (TypeError, ValueError):
        return False


def safe_diversity(data_lst: list[dict[str, Any]], metric_name: str, metric_func) -> tuple[Any | None, str | None]:
    """Compute one diversity metric without aborting the whole summary.

    Args:
        data_lst: Evaluation dictionaries for one grasp type.
        metric_name: Human-readable metric name for warning text.
        metric_func: Callable that returns one JSON-serializable metric value.

    Returns:
        Pair of diversity value and warning message. The diversity value is None if the
        metric cannot be computed.
    """

    try:
        with py_warnings.catch_warnings():
            py_warnings.simplefilter("ignore", RuntimeWarning)
            metric_value = metric_func(data_lst)
        if not metric_value_is_finite(metric_value):
            return None, f"skip {metric_name}: metric returned non-finite values"
        return metric_value, None
    except (KeyError, ValueError) as error:
        return None, f"skip {metric_name}: {error}"


def build_wrist_pose_diversity(
    data_lst: list[dict[str, Any]],
    wrist_approach_axes: Any,
) -> tuple[dict[str, Any | None], list[str]]:
    """Compute wrist-pose diversity metrics for successful grasps.

    Args:
        data_lst: Successful evaluation dictionaries used for diversity.
        wrist_approach_axes: Per-hand local approach axes read from hand config.

    Returns:
        Pair of JSON-serializable wrist-pose diversity metrics and warning messages.
    """

    metrics: dict[str, Any | None] = {}
    warnings = []
    for metric_name, metric_func in (
        (
            "approach_coverage",
            lambda data_lst: get_wrist_tabletop_approach_coverage(
                data_lst,
                local_axes=wrist_approach_axes,
            ),
        ),
        (
            "approach_pairwise_distance",
            lambda data_lst: get_wrist_approach_pairwise_distance(
                data_lst,
                local_axes=wrist_approach_axes,
            ),
        ),
        ("joint_position_pca", get_grasp_joint_pos_diversity),
    ):
        metric_value, warning = safe_diversity(data_lst, f"wrist_pose.{metric_name}", metric_func)
        metrics[metric_name] = metric_value
        if warning:
            warnings.append(warning)
    return metrics, warnings


def build_bimanual_relative_approach_diversity(
    data_lst: list[dict[str, Any]],
    wrist_approach_axes: Any,
) -> tuple[dict[str, Any | None], list[str]]:
    """Compute bimanual relative approach diversity metrics.

    Args:
        data_lst: Successful evaluation dictionaries used for diversity.
        wrist_approach_axes: Per-hand local approach axes read from hand config.

    Returns:
        Pair of JSON-serializable bimanual relative approach metrics and warning
        messages.
    """

    metrics: dict[str, Any | None] = {
        "applicable": True,
        "metric_source": "left_wrist_approach_axis_in_right_wrist_frame_positive_hemisphere",
        "note": (
            "Left wrist approach axis is expressed in the right wrist local frame. "
            "Coverage is computed on the positive hemisphere defined by the right "
            "hand local palm-side approach axis."
        ),
    }
    warnings = []
    first_global_pose = np.asarray(data_lst[0].get("grasp_global_pose", []), dtype=np.float32)
    if first_global_pose.size // 7 < 2:
        metrics.update(
            {
                "applicable": False,
                "hemisphere_coverage": None,
                "hemisphere_pairwise_distance": None,
                "angle_coverage": None,
                "angle_pairwise_distance": None,
            }
        )
        return metrics, warnings

    for metric_name, metric_func in (
        (
            "hemisphere_coverage",
            lambda data_lst: get_bimanual_relative_approach_geometry(
                data_lst,
                local_axes=wrist_approach_axes,
            ),
        ),
        (
            "hemisphere_pairwise_distance",
            lambda data_lst: get_bimanual_relative_approach_pairwise_distance(
                data_lst,
                local_axes=wrist_approach_axes,
            ),
        ),
    ):
        metric_value, warning = safe_diversity(data_lst, f"bimanual_relative_approach.{metric_name}", metric_func)
        metrics[metric_name] = metric_value
        if warning:
            warnings.append(warning)
    # Backward-compatible aliases for older JSON consumers.
    metrics["angle_coverage"] = metrics.get("hemisphere_coverage")
    metrics["angle_pairwise_distance"] = metrics.get("hemisphere_pairwise_distance")
    return metrics, warnings


def summarize_grasp_type(
    job: StatJob,
    records: list[EvalRecord],
    trans_thre: float,
    angle_thre: float,
    hand_geom_dist_thre: float,
) -> dict[str, Any]:
    """Summarize grasp-level and diversity metrics for one grasp type.

    Args:
        job: Stat job describing the grasp type.
        records: Loaded evaluation records for this grasp type.
        trans_thre: Translation threshold used to classify position-error failures.
        angle_thre: Rotation threshold in degrees used to classify rotation-only failures.
        hand_geom_dist_thre: Minimum allowed nearest hand-hand geom clearance in meters.

    Returns:
        JSON-serializable summary dictionary.
    """

    success_count = sum(record.success for record in records)
    eval_count = len(records)
    scene_ids = {record.scene_id for record in records}

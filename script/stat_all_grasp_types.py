@dataclass(frozen=True)
class StatJob:
    """Evaluation output location for one grasp type.

    Args:
        grasp_type: Canonical grasp type suffix, such as `right_two`.
        hand_name: Benchmark hand config name used for this grasp type.
        output_path: Root output folder generated by `process_all_grasp_types.py`.
        wrist_approach_axes: Per-hand local approach axes read from hand config.

    Returns:
        Dataclass instance describing one stat input folder.
    """

    grasp_type: str
    hand_name: str
    output_path: Path
    wrist_approach_axes: Any

    @property
    def eval_dir(self) -> Path:
        """Return the evaluation result directory.

        Args:
            None.

        Returns:
            Path to the folder containing evaluated `.npy` files.
        """

        return self.output_path / "evaluation"

    @property
    def succ_dir(self) -> Path:
        """Return the successful grasp directory.

        Args:
            None.

        Returns:
            Path to the folder containing successful grasp symlinks/files.
        """

        return self.output_path / "succgrasp"


@dataclass(frozen=True)
class EvalRecord:
    """Loaded evaluation sample with derived metadata.

    Args:
        scene_id: Scene identifier relative to the evaluation folder.
        success: Whether this grasp succeeded in simulation.
        data: Evaluation dictionary loaded from the `.npy` file.

    Returns:
        Dataclass instance used by the aggregate statistics.
    """

    scene_id: str
    success: bool
    data: dict[str, Any]


@dataclass(frozen=True)
class ObjectScaleStats:
    """Aggregated success statistics for one object scale.

    Args:
        scale_key: Stable printable scale key used in JSON output.
        evaluated_grasps: Number of evaluated grasps for this scale.
        successful_grasps: Number of successful grasps for this scale.

    Returns:
        Dataclass instance representing one object-scale row.
    """

    scale_key: str
    evaluated_grasps: int
    successful_grasps: int

    @property
    def success_rate(self) -> float | None:
        """Return grasp success rate for this scale.

        Args:
            None.

        Returns:
            Success rate, or None if no evaluated grasp exists.
        """

        if self.evaluated_grasps == 0:
            return None
        return float(self.successful_grasps / self.evaluated_grasps)



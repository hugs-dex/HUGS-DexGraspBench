def build_summary(args: argparse.Namespace) -> dict[str, Any]:
    """Build the full all-grasp-type comparison summary.

    Args:
        args: Parsed command line arguments.

    Returns:
        JSON-serializable aggregate summary.
    """

    jobs = build_stat_jobs(
        args.hand,
        args.run_name,
        Path(args.save_root),
        args.grasp_types,
        include_both_three=args.include_both_three,
    )
    records_by_type = {}
    per_type_summary = []
    warnings = []

    for job in jobs:
        records, job_warnings = load_eval_records(job, args.hand_geom_dist_thre)
        records_by_type[job.grasp_type] = records
        warnings.extend(job_warnings)
        per_type_summary.append(
            summarize_grasp_type(
                job,
                records,
                args.trans_thre,
                args.angle_thre,
                args.hand_geom_dist_thre,
            )
        )

    total_eval = sum(item["evaluated_grasps"] for item in per_type_summary)
    total_success = sum(item["successful_grasps"] for item in per_type_summary)
    scene_coverage = summarize_scene_coverage(records_by_type, len(jobs))
    object_scale_summary = summarize_object_scales(records_by_type)
    metric_sections = build_metric_sections(
        per_type_summary,
        object_scale_summary,
        scene_coverage,
        total_eval,
        total_success,
    )
    return {
        "hand": args.hand,
        "run_name": args.run_name,
        "save_root": args.save_root,
        "grasp_types": [job.grasp_type for job in jobs],
        "include_both_three": bool(args.include_both_three),
        "thresholds": {
            "trans_thre": float(args.trans_thre),
            "angle_thre": float(args.angle_thre),
            "self_pene_thre": 0.0,
            "hand_geom_dist_thre": float(args.hand_geom_dist_thre),
        },
        "diversity_success_only": True,
        "data_counts": metric_sections["data_counts"],
        "success_rates": metric_sections["success_rates"],
        "analytic_metrics": metric_sections["analytic_metrics"],
        "diversity": metric_sections["diversity"],
        "failure_reasons": metric_sections["failure_reasons"],
        "scene_coverage": scene_coverage,
        "overall": {
            "evaluated_grasps": int(total_eval),
            "successful_grasps": int(total_success),
            "success_rate": float(total_success / total_eval) if total_eval else None,
        },
        "per_object_scale": object_scale_summary,
        "per_grasp_type": per_type_summary,
        "warnings": warnings,
    }


def save_json_summary(summary: dict[str, Any], json_path: Path) -> None:
    """Save the aggregate summary as formatted JSON.

    Args:
        summary: JSON-serializable aggregate summary.
        json_path: Output JSON path.

    Returns:
        None.
    """

    json_path.parent.mkdir(parents=True, exist_ok=True)
    with json_path.open("w", encoding="utf-8") as file:
        json.dump(summary, file, indent=2)
        file.write("\n")


def main(argv: list[str] | None = None) -> int:
    """Run the all-grasp-type statistic script.

    Args:
        argv: Optional argument list for tests; None uses `sys.argv`.

    Returns:
        Process exit code.
    """

    parser = build_parser()
    args = parser.parse_args(argv)
    summary = build_summary(args)
    print_summary(summary)

    if summary["overall"]["evaluated_grasps"] == 0:
        print("No evaluated grasps found for the selected run.", file=sys.stderr)
        return 1

    if not args.no_json:
        json_path = Path(args.json_path) if args.json_path else Path(args.save_root) / f"{args.run_name}_{args.hand}_all_grasp_type_stats.json"
        save_json_summary(summary, json_path)
        print()
        print(f"Saved JSON summary: {json_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

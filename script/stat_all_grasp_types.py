def summarize_scene_coverage(records_by_type: dict[str, list[EvalRecord]], grasp_type_num: int) -> dict[str, Any]:
    """Summarize how many successful grasp types each scene has.

    Args:
        records_by_type: Mapping from grasp type to loaded evaluation records.
        grasp_type_num: Number of grasp types included in this comparison.

    Returns:
        JSON-serializable scene coverage summary.
    """

    all_scene_ids = set()
    successful_types_by_scene: dict[str, set[str]] = defaultdict(set)
    for grasp_type, records in records_by_type.items():
        for record in records:
            all_scene_ids.add(record.scene_id)
            if record.success:
                successful_types_by_scene[record.scene_id].add(grasp_type)

    successful_type_count_by_scene = {
        scene_id: len(successful_types_by_scene.get(scene_id, set())) for scene_id in all_scene_ids
    }
    histogram = Counter(successful_type_count_by_scene.values())
    scene_num = len(all_scene_ids)
    distribution = {}
    for type_count in range(grasp_type_num + 1):
        count = histogram.get(type_count, 0)
        distribution[str(type_count)] = {
            "scene_count": int(count),
            "scene_percent": float(count / scene_num) if scene_num else None,
        }

    average_successful_type_num = (
        float(np.mean(list(successful_type_count_by_scene.values()))) if successful_type_count_by_scene else None
    )
    return {
        "evaluated_scenes": scene_num,
        "successful_scenes": int(sum(1 for type_count in successful_type_count_by_scene.values() if type_count > 0)),
        "scene_success_rate": (
            float(sum(1 for type_count in successful_type_count_by_scene.values() if type_count > 0) / scene_num)
            if scene_num
            else None
        ),
        "average_successful_grasp_type_num": average_successful_type_num,
        "successful_grasp_type_count_distribution": distribution,
    }


def summarize_object_scales(records_by_type: dict[str, list[EvalRecord]]) -> list[dict[str, Any]]:
    """Summarize evaluated/successful grasps and qp metrics by object scale.

    Args:
        records_by_type: Mapping from grasp type to loaded evaluation records.

    Returns:
        Ordered list of JSON-serializable object-scale statistics.
    """

    evaluated_counts = Counter()
    successful_counts = Counter()
    records_by_scale: dict[str, list[EvalRecord]] = defaultdict(list)
    successful_records_by_scale: dict[str, list[EvalRecord]] = defaultdict(list)
    for records in records_by_type.values():
        for record in records:
            scale_key = object_scale_key_from_data(record.data)
            evaluated_counts[scale_key] += 1
            records_by_scale[scale_key].append(record)
            if record.success:
                successful_counts[scale_key] += 1
                successful_records_by_scale[scale_key].append(record)

    scale_stats = []
    for scale_key in sorted(evaluated_counts, key=object_scale_sort_key):
        item = ObjectScaleStats(
            scale_key=scale_key,
            evaluated_grasps=int(evaluated_counts[scale_key]),
            successful_grasps=int(successful_counts[scale_key]),
        )
        scale_stats.append(
            {
                "object_scale": item.scale_key,
                "evaluated_grasps": item.evaluated_grasps,
                "successful_grasps": item.successful_grasps,
                "success_rate": item.success_rate,
                "qp_metric": summarize_scalar_metric(records_by_scale[scale_key], "qp_metric"),
                "qp_metric_success": summarize_scalar_metric(successful_records_by_scale[scale_key], "qp_metric"),
            }
        )
    return scale_stats


def build_metric_sections(
    per_type_summary: list[dict[str, Any]],
    object_scale_summary: list[dict[str, Any]],
    scene_coverage: dict[str, Any],
    total_eval: int,
    total_success: int,
) -> dict[str, Any]:
    """Organize metrics into plotting/table friendly JSON sections.

    Args:
        per_type_summary: Per-grasp-type summary dictionaries.
        object_scale_summary: Object-scale summary dictionaries.
        scene_coverage: Scene-level successful grasp-type coverage summary.
        total_eval: Total number of evaluated grasps across selected types.
        total_success: Total number of successful grasps across selected types.

    Returns:
        Dictionary with `data_counts`, `success_rates`, `diversity`, and
        `failure_reasons` sections.
    """

    per_type_counts = {
        item["grasp_type"]: {
            "evaluated_grasps": item["evaluated_grasps"],
            "successful_grasps": item["successful_grasps"],
        }
        for item in per_type_summary
    }
    per_type_sr = {
        item["grasp_type"]: item["success_rate"]
        for item in per_type_summary
    }
    per_type_qp_metric = {
        item["grasp_type"]: item["qp_metric"]
        for item in per_type_summary
    }
    per_type_qp_metric_success = {
        item["grasp_type"]: item["qp_metric_success"]
        for item in per_type_summary
    }
    per_scale_counts = {
        item["object_scale"]: {
            "evaluated_grasps": item["evaluated_grasps"],
            "successful_grasps": item["successful_grasps"],
        }
        for item in object_scale_summary
    }
    per_scale_sr = {
        item["object_scale"]: item["success_rate"]
        for item in object_scale_summary
    }
    per_scale_qp_metric = {
        item["object_scale"]: item["qp_metric"]
        for item in object_scale_summary
    }
    per_scale_qp_metric_success = {
        item["object_scale"]: item["qp_metric_success"]
        for item in object_scale_summary
    }
    per_type_diversity = {
        item["grasp_type"]: {
            "diversity_success_only": item["diversity_success_only"],
            "diversity_grasps": item["diversity_grasps"],
            "wrist_pose": item["diversity"]["wrist_pose"],
            "bimanual_relative_approach": item["diversity"]["bimanual_relative_approach"],
            "bimanual_fingertip_angle": item["diversity"]["bimanual_fingertip_angle"],
        }
        for item in per_type_summary
    }
    return {
        "data_counts": {
            "total_grasps": int(total_eval),
            "total_successful_grasps": int(total_success),
            "by_grasp_type": per_type_counts,
            "by_object_scale": per_scale_counts,
        },
        "success_rates": {
            "overall": float(total_success / total_eval) if total_eval else None,
            "scene": scene_coverage["scene_success_rate"],
            "by_grasp_type": per_type_sr,
            "by_object_scale": per_scale_sr,
        },
        "analytic_metrics": {
            "qp_metric": {
                "by_grasp_type": per_type_qp_metric,
                "by_object_scale": per_scale_qp_metric,
            },
            "qp_metric_success": {
                "by_grasp_type": per_type_qp_metric_success,
                "by_object_scale": per_scale_qp_metric_success,
            },
        },
        "diversity": {
            "success_only": True,
            "grasp_type_scene_coverage": {
                "average_successful_grasp_type_num": scene_coverage["average_successful_grasp_type_num"],
                "successful_grasp_type_count_distribution": scene_coverage[
                    "successful_grasp_type_count_distribution"
                ],
            },
            "by_grasp_type": per_type_diversity,
        },
        "failure_reasons": {
            "by_grasp_type": {
                item["grasp_type"]: item["failure_reasons"]
                for item in per_type_summary
            },
        },
    }


def format_rate(value: float | None) -> str:
    """Format a rate for terminal output.

    Args:
        value: Optional floating point rate.

    Returns:
        Percent string or `n/a`.
    """

    return "n/a" if value is None else f"{100.0 * value:.2f}%"


def format_diversity(value: list[float] | None) -> str:
    """Format a PCA diversity list for terminal output.

    Args:
        value: Optional list of cumulative explained variance ratios.

    Returns:
        Compact printable representation.
    """

    if value is None:
        return "n/a"
    return "[" + ", ".join(f"{item:.4f}" for item in value) + "]"


def format_metric(value: Any | None) -> str:
    """Format a diversity metric for terminal output.

    Args:
        value: Optional metric value. Lists are printed as compact numeric arrays;
            dictionaries print their most important coverage/statistic fields.

    Returns:
        Compact printable representation.
    """

    if value is None:
        return "n/a"
    if isinstance(value, list):
        return format_diversity(value)
    if isinstance(value, dict):
        if "pair_num" in value:
            unit = "deg" if value.get("distance_unit") == "degree" else value.get("distance_unit", "")
            pair_text = str(value["pair_num"])
            if value.get("estimated"):
                pair_text = f"{value['sampled_pair_num']}/{value['total_pair_num']}"
            return (
                f"mean={value['mean']:.2f}{unit}, std={value['std']:.2f}{unit}, "
                f"median={value['median']:.2f}{unit}, pairs={pair_text}"
            )
        if "coverage" in value:
            formatted = f"{100.0 * value['coverage']:.2f}%({value['occupied_bins']}/{value['total_bins']})"
            if "polar_coverage" in value:
                formatted += (
                    f", polar={100.0 * value['polar_coverage']:.2f}%"
                    f"({value['occupied_polar_bins']}/{value['total_polar_bins']})"
                )
            if "plane_angle_coverage" in value:
                formatted += (
                    f", angle={100.0 * value['plane_angle_coverage']:.2f}%"
                    f"({value['occupied_plane_angle_bins']}/{value['total_plane_angle_bins']})"
                )
            if "azimuth_coverage" in value:
                formatted += (
                    f", az={100.0 * value['azimuth_coverage']:.2f}%"
                    f"({value['occupied_azimuth_bins']}/{value['total_azimuth_bins']})"
                )
            if "below_table_percent" in value:
                formatted += f", below={100.0 * value['below_table_percent']:.2f}%"
            if "negative_hemisphere_percent" in value:
                formatted += f", neg={100.0 * value['negative_hemisphere_percent']:.2f}%"
            return formatted
        if "theta_coverage" in value:
            return (
                f"theta={value['theta_mean_deg']:.2f}+/-{value['theta_std_deg']:.2f}deg, "
                f"cov={100.0 * value['theta_coverage']:.2f}%({value['occupied_bins']}/{value['total_bins']})"
            )
    return str(value)


def format_scalar_metric_summary(metric_summary: dict[str, Any] | None) -> str:
    """Format scalar metric statistics for terminal output.

    Args:
        metric_summary: Summary generated by `summarize_scalar_metric`.

    Returns:
        Compact text with count, mean, and median, or `n/a` when unavailable.
    """

    if not metric_summary or metric_summary.get("count", 0) == 0:
        return "n/a"
    return (
        f"n={metric_summary['count']}, "
        f"mean={metric_summary['mean']:.4g}, "
        f"median={metric_summary['median']:.4g}"
    )


def format_failure_reasons(failure_reasons: dict[str, Any]) -> str:
    """Format failure reason percentages for terminal output.

    Args:
        failure_reasons: Failure-reason summary generated by `summarize_failure_reasons`.

    Returns:
        Compact string with percentages among failed grasps.
    """

    reason_labels = (
        ("pregrasp_severe_penetration", "pene"),
        ("self_penetration", "self"),
        ("self_geom_distance", "geom"),
        ("position_error", "pos"),
        ("rotation_error", "rot"),
        ("unknown", "unknown"),
    )
    reason_items = failure_reasons["by_reason"]
    return ", ".join(
        f"{label}={format_rate(reason_items[reason]['failed_percent'])}({reason_items[reason]['count']})"
        for reason, label in reason_labels
    )


